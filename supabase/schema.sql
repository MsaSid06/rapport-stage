create table if not exists public.rapports (
  id bigint generated by default as identity primary key,
  date date not null,
  jour_stage integer not null check (jour_stage >= 1),
  objectif text not null,
  activites text not null,
  difficultes text,
  solutions text,
  apprentissages text,
  bilan text,
  demain text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists rapports_date_idx on public.rapports (date desc);
create index if not exists rapports_jour_stage_idx on public.rapports (jour_stage);

-- Cette application n'a pas d'authentification : ces règles permettent l'accès public.
-- À utiliser uniquement si le contenu ne contient aucune donnée confidentielle.
alter table public.rapports enable row level security;
drop policy if exists "Accès public rapports lecture" on public.rapports;
drop policy if exists "Accès public rapports insertion" on public.rapports;
drop policy if exists "Accès public rapports modification" on public.rapports;
drop policy if exists "Accès public rapports suppression" on public.rapports;
create policy "Accès public rapports lecture" on public.rapports for select to anon, authenticated using (true);
create policy "Accès public rapports insertion" on public.rapports for insert to anon, authenticated with check (true);
create policy "Accès public rapports modification" on public.rapports for update to anon, authenticated using (true) with check (true);
create policy "Accès public rapports suppression" on public.rapports for delete to anon, authenticated using (true);
